test("encrypted storage setup submits confirmation and passwords, then opens the saved-settings wizard", async () => {
  const base = preview(() => {})
  const initial = status.parse(JSON.parse(await base.request({ operation: "status" })))
  let current = { ...initial, general_present: false, general_open: false, general_mounted: false, sessions: [] }
  const mutations: string[] = []
  const runtime = { ...base, request: async (input: Parameters<typeof base.request>[0]) => {
    if (input.operation === "status") return JSON.stringify(current)
    if (input.operation === "prepare-usb") {
      expect(JSON.parse(new TextDecoder().decode(input.payload))).toEqual({ plan: initial.persistence!.plan, password: "synthetic-archive-password" })
      mutations.push(input.operation)
      current = { ...current, general_present: true }
      return ""
    }
    if (input.operation === "unlock") {
      expect(new TextDecoder().decode(input.payload)).toBe("synthetic-archive-password")
      mutations.push(input.operation)
      current = { ...current, general_open: true, general_mounted: true }
      return ""
    }
    return base.request(input)
  } }
  const app = await testRender(() => <App runtime={runtime} initial={current} />, { width: 80, height: 24, kittyKeyboard: true })
  try {
    await app.renderOnce()
    expect(app.captureCharFrame()).toContain("ACCESS / First-time setup")
    expect(app.captureCharFrame()).toContain("Create encrypted storage")
    expect(app.captureCharFrame().match(/Keyboard (?:& time zone|\/ Time)/g)).toHaveLength(1)
    expect(app.captureCharFrame()).not.toContain("Test keyboard")
    expect(app.captureCharFrame()).not.toContain("USB")
    await app.mockInput.pressEnter()
    await app.mockInput.pressArrow("down")
    await app.mockInput.pressEnter()
    await app.mockInput.typeText("synthetic-archive-password")
    await app.mockInput.pressEnter()
    await app.mockInput.typeText("synthetic-archive-password")
    await app.mockInput.pressEnter()
    await app.mockInput.pressEnter()
    await app.renderOnce()
    expect(mutations).toEqual(["prepare-usb", "unlock"])
    expect(app.captureCharFrame()).toContain("HOST / Sessions")
    expect(app.captureCharFrame()).toContain("Keyboard / Layout")
    await app.mockInput.pressEscape()
    await app.renderOnce()
    expect(app.captureCharFrame()).toContain("New session")
  } finally { app.renderer.destroy(); await app.renderer.closed }
})

test("controller errors retain their specific message and allow another unlock attempt", async () => {
  const base = preview(() => {})
  await base.request({ operation: "lock" })
  const initial = status.parse(JSON.parse(await base.request({ operation: "status" })))
  const attempts: string[] = []
  const runtime = { ...base, request: async (input: Parameters<typeof base.request>[0]) => {
    if (input.operation !== "unlock") return base.request(input)
    attempts.push(new TextDecoder().decode(input.payload))
    if (attempts.length === 1) throw new ControlError("volume_unlock_failed")
    return base.request(input)
  } }
  const app = await testRender(() => <App runtime={runtime} initial={initial} />, { width: 80, height: 24, kittyKeyboard: true })
  try {
    await app.renderOnce()
    await app.mockInput.pressEnter()
    await app.mockInput.typeText("wrong-password")
    await app.mockInput.pressEnter()
    await app.mockInput.pressEnter()
    await app.renderOnce()
    expect(app.captureCharFrame()).toContain("The volume could not be unlocked.")
    expect(app.captureCharFrame()).toContain("Welcome back")
    await app.mockInput.pressEnter()
    await app.mockInput.typeText("correct-password")
    await app.mockInput.pressEnter()
    await app.mockInput.pressEnter()
    await app.renderOnce()
    expect(attempts).toEqual(["wrong-password", "correct-password"])
    expect(app.captureCharFrame()).toContain("HOST / Sessions")
  } finally { app.renderer.destroy(); await app.renderer.closed }
})

